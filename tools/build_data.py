"""Generate ../data.js from data_src/*.py.  Run: python3 tools/build_data.py"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "data_src"))
import helpers
for mod in ["pdf_ch1_ch2", "pdf_ch3", "pdf_ch4", "pdf_ch5_ch6", "lab_extras"]:
    __import__(mod)

TOPICS = [
    {"id": "ct",    "no": "01", "title": "Computational Thinking", "short": "COMPUTATIONAL THINKING", "color": "#22C55E"},
    {"id": "alg",   "no": "02", "title": "Problem Solving: Algorithms, Pseudocode & Flowcharts", "short": "ALGORITHMS & FLOWCHARTS", "color": "#3B82F6"},
    {"id": "cpp",   "no": "03", "title": "Basics of C++ Programming", "short": "BASICS OF C++", "color": "#EAB308"},
    {"id": "ctrl",  "no": "04", "title": "Control Structures (if, switch, loops)", "short": "CONTROL STRUCTURES", "color": "#EF4444"},
    {"id": "func",  "no": "05", "title": "Functions", "short": "FUNCTIONS", "color": "#A855F7"},
    {"id": "cheat", "no": "06", "title": "Ulangkaji Cheat Sheet", "short": "ONE-PAGE CHEAT SHEET", "color": "#38BDF8"},
]
ids = {t["id"] for t in TOPICS}
for s in helpers.ALL:
    assert s["topic"] in ids, s["id"]
    if s["type"] == "explain":
        assert s["keywords"], s["id"]
    else:
        assert s["answer"], s["id"]
order = {t["id"]: i for i, t in enumerate(TOPICS)}
helpers.ALL.sort(key=lambda s: (order[s["topic"]], s["id"].startswith("x")))
out = {"version": 2, "topics": TOPICS, "statements": helpers.ALL}
js = ("/* SCSE1013 notes data. Generated by tools/build_data.py.\n"
      "   You can edit this file directly, or use the 'Urus Nota' page in the app. */\n"
      "window.SCSE_DEFAULT_DATA = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
open(os.path.join(HERE, "..", "data.js"), "w", encoding="utf-8").write(js)
from collections import Counter
print(len(helpers.ALL), "statements", dict(Counter(s["topic"] for s in helpers.ALL)),
      "followUps", sum(len(s["followUps"]) for s in helpers.ALL),
      "trap", sum(s["trap"] for s in helpers.ALL))
